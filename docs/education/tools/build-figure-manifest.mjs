/**
 * Build docs/education/FIGURES.md — the tracked provenance record for every
 * third-party figure the education site references.
 *
 *   node docs/education/tools/build-figure-manifest.mjs
 *
 * WHY THIS EXISTS
 * ---------------
 * The figures on this site are Kenneth Libbrecht's, and they are copyrighted.
 * Decision 0004 (docs/decisions/0004-research-media-not-versioned.md) settled
 * that research media is NOT committed to this repository: committing it would
 * publish it on the first push, and git history would make that permanent.
 *
 * So the site references figures by path into the gitignored research/ cache,
 * and every reference degrades to a fully-cited placeholder when the cache is
 * absent (see assets/site.js). THIS FILE is the tracked artifact: it records
 * what each figure is, which paper and page it came from, and its sha256 when
 * present locally — exactly the discipline research/figures.md already applies.
 *
 * The manifest is generated by scanning the chapters rather than hand-kept, so
 * it cannot drift from what the site actually shows.
 */

import { createHash } from "node:crypto";
import { readFileSync, readdirSync, existsSync, writeFileSync, statSync } from "node:fs";
import { join, resolve } from "node:path";

const REPO = resolve(import.meta.dirname, "../../..");
const CHAPTERS = join(REPO, "docs/education/chapters");
const OUT = join(REPO, "docs/education/FIGURES.md");
// A rendered twin of the manifest, so the provenance record is readable on the
// published site — GitHub Pages serves .md as plain text.
const OUT_HTML = join(REPO, "docs/education/figures.html");

/** Pull every <figure class="figure" data-…> block out of a chapter file. */
function extractFigures(html, chapterFile) {
  const out = [];
  const re = /<figure\b[^>]*\bdata-src=["']([^"']+)["'][^>]*>/g;
  let m;
  while ((m = re.exec(html)) !== null) {
    const tag = m[0];
    const attr = (name) => {
      const a = new RegExp(`\\bdata-${name}=["']([^"']*)["']`).exec(tag);
      return a ? a[1] : "";
    };
    out.push({
      src: m[1],
      figure: attr("figure"),
      source: attr("source"),
      page: attr("page"),
      alt: attr("alt"),
      chapter: chapterFile,
    });
  }
  return out;
}

function sha256(path) {
  try {
    return createHash("sha256").update(readFileSync(path)).digest("hex");
  } catch {
    return null;
  }
}

const chapterFiles = existsSync(CHAPTERS)
  ? readdirSync(CHAPTERS).filter((f) => f.endsWith(".html")).sort()
  : [];

const rows = [];
for (const file of chapterFiles) {
  const html = readFileSync(join(CHAPTERS, file), "utf8");
  rows.push(...extractFigures(html, file));
}

// Deduplicate by src, remembering every chapter that uses it.
const bySrc = new Map();
for (const r of rows) {
  const existing = bySrc.get(r.src);
  if (existing) {
    if (!existing.chapters.includes(r.chapter)) existing.chapters.push(r.chapter);
  } else {
    bySrc.set(r.src, { ...r, chapters: [r.chapter] });
  }
}

const figures = [...bySrc.values()].sort((a, b) => a.src.localeCompare(b.src));

let present = 0;
for (const f of figures) {
  const abs = join(REPO, f.src);
  if (existsSync(abs)) {
    present++;
    f.bytes = statSync(abs).size;
    f.sha256 = sha256(abs);
  }
}

const lines = [];
