/**
 * Build docs/education/FIGURES.md — the tracked provenance record for source-figure
 * references discovered in the education chapters' `data-src` metadata.
 *
 *   node docs/education/tools/build-figure-manifest.mjs
 *
 * WHY THIS EXISTS
 * ---------------
 * The figures on this site are third-party copyrighted research media.
 * Decision 0004 (docs/decisions/0004-research-media-not-versioned.md) settled
 * that those bytes are NOT committed to this repository: committing them would
 * publish them on the first push, and git history would make that permanent.
 *
 * So the site references figures by path into the gitignored research/ cache,
 * and every reference degrades to a fully-cited placeholder when the cache is
 * absent (see assets/site.js). THIS FILE is the tracked artifact: it records
 * what each figure is, which paper and page it came from, and its sha256 when
 * present locally — exactly the discipline research/figures.md already applies.
 *
 * The manifest is generated by scanning the chapters rather than hand-kept, so
 * it cannot drift from what the site actually shows.
 */

import { createHash } from "node:crypto";
import { readFileSync, readdirSync, existsSync, writeFileSync, statSync } from "node:fs";
import { join, resolve } from "node:path";

const REPO = resolve(import.meta.dirname, "../../..");
const CHAPTERS = join(REPO, "docs/education/chapters");
const OUT = join(REPO, "docs/education/FIGURES.md");
// A rendered twin of the manifest, so the provenance record is readable on the
// published site — GitHub Pages serves .md as plain text.
