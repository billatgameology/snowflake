/**
 * Build docs/education/FIGURES.md — the tracked provenance record for every
 * third-party figure the education site references.
 *
 *   node docs/education/tools/build-figure-manifest.mjs
 *
 * WHY THIS EXISTS
 * ---------------
 * The figures on this site are Kenneth Libbrecht's, and they are copyrighted.
 * Decision 0004 (docs/decisions/0004-research-media-not-versioned.md) settled
 * that research media is NOT committed to this repository: committing it would
 * publish it on the first push, and git history would make that permanent.
 *
 * So the site references figures by path into the gitignored research/ cache,
 * and every reference degrades to a fully-cited placeholder when the cache is
 * absent (see assets/site.js). THIS FILE is the tracked artifact: it records
 * what each figure is, which paper and page it came from, and its sha256 when
 * present locally — exactly the discipline research/figures.md already applies.
 *
 * The manifest is generated by scanning the chapters rather than hand-kept, so
 * it cannot drift from what the site actually shows.
 */

import { createHash } from "node:crypto";
import { readFileSync, readdirSync, existsSync, writeFileSync, statSync } from "node:fs";
import { join, resolve } from "node:path";

const REPO = resolve(import.meta.dirname, "../../..");
const CHAPTERS = join(REPO, "docs/education/chapters");
const OUT = join(REPO, "docs/education/FIGURES.md");

/** Pull every <figure class="figure" data-…> block out of a chapter file. */
function extractFigures(html, chapterFile) {
  const out = [];
  const re = /<figure\b[^>]*\bdata-src=["']([^"']+)["'][^>]*>/g;
  let m;
  while ((m = re.exec(html)) !== null) {
    const tag = m[0];
    const attr = (name) => {
      const a = new RegExp(`\\bdata-${name}=["']([^"']*)["']`).exec(tag);
      return a ? a[1] : "";
    };
    out.push({
      src: m[1],
      figure: attr("figure"),
      source: attr("source"),
      page: attr("page"),
      alt: attr("alt"),
      chapter: chapterFile,
    });
  }
  return out;
}

function sha256(path) {
  try {
    return createHash("sha256").update(readFileSync(path)).digest("hex");
  } catch {
    return null;
  }
}

const chapterFiles = existsSync(CHAPTERS)
  ? readdirSync(CHAPTERS).filter((f) => f.endsWith(".html")).sort()
  : [];

const rows = [];
for (const file of chapterFiles) {
  const html = readFileSync(join(CHAPTERS, file), "utf8");
  rows.push(...extractFigures(html, file));
}

// Deduplicate by src, remembering every chapter that uses it.
const bySrc = new Map();
for (const r of rows) {
  const existing = bySrc.get(r.src);
  if (existing) {
    if (!existing.chapters.includes(r.chapter)) existing.chapters.push(r.chapter);
  } else {
    bySrc.set(r.src, { ...r, chapters: [r.chapter] });
  }
}

const figures = [...bySrc.values()].sort((a, b) => a.src.localeCompare(b.src));

let present = 0;
for (const f of figures) {
  const abs = join(REPO, f.src);
  if (existsSync(abs)) {
    present++;
    f.bytes = statSync(abs).size;
    f.sha256 = sha256(abs);
  }
}

const lines = [];
lines.push("# Education site — figure provenance");
lines.push("");
lines.push("**Generated. Do not edit by hand** — run:");
lines.push("");
lines.push("```");
lines.push("node docs/education/tools/build-figure-manifest.mjs");
lines.push("```");
lines.push("");
lines.push(
  "Every third-party figure the education site references, with the paper, page, and local " +
  "sha256 it was recorded at. The images themselves are **not versioned** — they are Kenneth " +
  "Libbrecht's copyrighted work, and [decision 0004](../decisions/0004-research-media-not-versioned.md) " +
  "keeps research media out of git. This file is the tracked record; the bytes are a cache."
);
lines.push("");
lines.push("## Why a figure may not appear on the site");
lines.push("");
lines.push(
  "If you opened a chapter and saw a hatched placeholder instead of a figure, the local cache " +
  "is missing that file. The site is fully usable without it: the explanation, the original " +
  "diagrams, and every animation are ours and always render. Only the scanned source figures " +
  "depend on the cache."
);
lines.push("");
lines.push("## How to restore the images locally");
lines.push("");
lines.push("1. **Re-download the papers** listed in [`research/libbrecht-later-papers.md`](../../research/libbrecht-later-papers.md)");
lines.push("   and [`research/1910.06389v2-llm.md`](../../research/1910.06389v2-llm.md). Both carry every source URL and sha256.");
lines.push("2. **Rebuild the monograph figure bundle** (supplies `research/1910.06389v2-llm/figures/fig-*/visual.png`):");
lines.push("   ```");
lines.push("   python3 scripts/build_pdf_llm_bundle.py --force research/1910.06389v2.pdf");
lines.push("   ```");
lines.push("3. **Rebuild the post-monograph crops** (supplies `research/figures/*.png`):");
lines.push("   ```");
lines.push("   node app/scripts/phase6-crop-figures.mjs");
lines.push("   ```");
lines.push("");
lines.push("## Status of this checkout");
lines.push("");
lines.push(`- Figures referenced by the site: **${figures.length}**`);
lines.push(`- Present in the local cache right now: **${present}**`);
lines.push(`- Missing (will render as a cited placeholder): **${figures.length - present}**`);
lines.push("");
lines.push("## The figures");
lines.push("");
lines.push("| figure | source | page | used in | bytes | sha256 |");
lines.push("|---|---|---|---|---:|---|");
for (const f of figures) {
  const chapters = f.chapters.map((c) => `\`${c}\``).join(", ");
  lines.push(
    `| ${f.figure || "—"} | ${f.source || "—"} | ${f.page || "—"} | ${chapters} | ` +
    `${f.bytes != null ? f.bytes.toLocaleString() : "*absent*"} | ` +
    `${f.sha256 ? "`" + f.sha256 + "`" : "*absent*"} |`
  );
}
lines.push("");
lines.push("### Paths");
lines.push("");
lines.push("| figure | path |");
lines.push("|---|---|");
for (const f of figures) {
  lines.push(`| ${f.figure || "—"} | \`${f.src}\` |`);
}
lines.push("");

writeFileSync(OUT, lines.join("\n"), "utf8");

console.log(`Wrote ${OUT}`);
console.log(`  ${figures.length} figures referenced across ${chapterFiles.length} chapters`);
console.log(`  ${present} present locally, ${figures.length - present} absent`);
